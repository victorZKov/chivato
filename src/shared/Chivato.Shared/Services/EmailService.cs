        IEnumerable<CredentialStatus> expiringCredentials,
        CancellationToken cancellationToken = default)
    {
        if (!recipients.Any()) return;

        // Implementation stub - In a real scenario, this would send an email similar to the drift report
        _logger.LogInformation("Simulating sending credential expiration warning to {Count} recipients", recipients.Count());
        await Task.CompletedTask;
    }

    public async Task<bool> TestConnectionAsync(string connectionString, string fromEmail)
    {
        try
        {
            var client = new EmailClient(connectionString);
            // Just verifying we can create the client. To really test, we might need to send a dummy email?
            // But usually validation happens on send. 
            // We can assume valid if connection string format is OK. 
            // A more robust check would try to list operations or something if permissions allow, 
            // but Azure Communication Services is send-centric.
            
            return await Task.FromResult(true);
        }
        catch (Exception ex)
        {
            _logger.LogError(ex, "Email connection test failed");
            return false;
        }
    }
}
